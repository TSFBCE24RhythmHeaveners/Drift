#!/usr/bin/env python3
"""Write docs/theming-tokens.md from the built-in dark and light theme documents.

The tables list the source values, including $references, not the resolved colors.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DARK_PATH = ROOT / "resources" / "themes" / "dark.json"
LIGHT_PATH = ROOT / "resources" / "themes" / "light.json"
OUT_PATH = ROOT / "docs" / "theming-tokens.md"

GROUPS = ("palette", "semantic", "components", "metrics", "typography", "motion", "window")


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def flatten(value, prefix: str = "") -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    if isinstance(value, dict):
        for key, child in value.items():
            path = f"{prefix}.{key}" if prefix else key
            rows.extend(flatten(child, path))
        return rows
    if isinstance(value, list):
        rendered = json.dumps(value, ensure_ascii=False, separators=(", ", ": "))
        return [(prefix, rendered)]
    if isinstance(value, str):
        return [(prefix, value)]
    if isinstance(value, bool):
        return [(prefix, "true" if value else "false")]
    return [(prefix, json.dumps(value))]


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(cell(column) for column in row) + " |")
    return "\n".join(lines)


def paired(dark_value, light_value) -> list[list[str]]:
    dark_rows = dict(flatten(dark_value))
    light_rows = dict(flatten(light_value))
    keys = list(dark_rows)
    for key in light_rows:
        if key not in dark_rows:
            keys.append(key)
    return [[key, dark_rows.get(key, ""), light_rows.get(key, "")] for key in keys]


def main() -> None:
    dark = load(DARK_PATH)
    light = load(LIGHT_PATH)
    parts = [
        "# Drift theme tokens",
        "",
        "Generated by `scripts/gen-theme-tokens.py` from `resources/themes/dark.json` and "
        "`resources/themes/light.json`. Do not edit by hand.",
        "",
        "Values are the document text. `$palette` and `$semantic` references are unresolved here; "
        "Drift resolves them when the theme loads. Colors are `#RRGGBB` or `#AARRGGBB` (alpha first).",
        "",
    ]
    for group in GROUPS:
        parts.append(f"## {group}")
        parts.append("")
        if group == "components":
            dark_components = dark.get("components", {})
            light_components = light.get("components", {})
            names = list(dark_components)
            for name in light_components:
                if name not in dark_components:
                    names.append(name)
            rows: list[list[str]] = []
            for name in names:
                for key, dark_value, light_value in paired(
                    dark_components.get(name, {}), light_components.get(name, {})
                ):
                    rows.append([name, key, dark_value, light_value])
            parts.append(table(["group", "key", "dark", "light"], rows))
        else:
            parts.append(table(["token", "dark", "light"], paired(dark.get(group, {}), light.get(group, {}))))
        parts.append("")
    OUT_PATH.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
